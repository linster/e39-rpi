// --- Protobuf / gRPC code, generated at build time (not committed) --------
//
// The .proto files in src/desktopMain/proto/<folder>/ are compiled by protoc
// into build/generated/proto/desktopMain: messages (Java + Kotlin DSL),
// grpc-java stubs and grpc-kotlin coroutine stubs. protoc and the plugins
// are Maven artifacts resolved by Gradle like the libraries (so image builds
// fetch and cache them in GRADLE_USER_HOME too). Their versions must match
// the runtime libraries above: code from a newer protoc refuses to load with
// an older protobuf-java.
//
// Which protos: the folders listed here, each with the include root its
// imports are relative to (protoc runs once per folder). (e39pim_api's code
// is still generated by makePimProtos.sh and committed; add it here, as
// e39maps_api, and delete src/desktopMain/java/ca/stefanm/e39pim to switch
// it over.)
val generatedProtoApis = mapOf(
    // The maps backend's API (copied from e39-rpi-maps by makeMapsProtos.sh):
    // imports "e39maps_api/v1/common.proto".
    "e39maps_api" to ".",
    // The Pi <-> Pico messages (also used by the Pico firmware): import
    // each other as "ConfigProto.proto".
    "pico" to "pico",
)
val protobufVersion = "4.28.2"     // = com.google.protobuf:protobuf-java
val grpcJavaVersion = "1.85.1"     // = io.grpc:grpc-*
val grpcKotlinVersion = "1.5.0"    // = io.grpc:grpc-kotlin-stub

/** protoc's and protoc-gen-grpc-java's classifier for the build machine. */
val protocClassifier: String = run {
    val os = System.getProperty("os.name").lowercase()
    val arch = when (System.getProperty("os.arch")) {
        "amd64", "x86_64" -> "x86_64"
        "aarch64", "arm64" -> "aarch_64"
        else -> error("protoc: unsupported build machine architecture ${System.getProperty("os.arch")}")
    }
    when {
        os.contains("linux") -> "linux-$arch"
        os.contains("mac") -> "osx-$arch"
        os.contains("windows") -> "windows-$arch"
        else -> error("protoc: unsupported build machine OS $os")
    }
}

val protocTools: Configuration by configurations.creating { isTransitive = false }
dependencies {
    protocTools("com.google.protobuf:protoc:$protobufVersion:$protocClassifier@exe")
    protocTools("io.grpc:protoc-gen-grpc-java:$grpcJavaVersion:$protocClassifier@exe")
    protocTools("io.grpc:protoc-gen-grpc-kotlin:$grpcKotlinVersion:jdk8@jar")
    // The well-known types (google/protobuf/empty.proto, ...) aren't in
    // protoc's download; protobuf-java's jar carries them.
    protocTools("com.google.protobuf:protobuf-java:$protobufVersion")
}

val protoSourceDir = layout.projectDirectory.dir("src/desktopMain/proto")
val generatedProtoDir = layout.buildDirectory.dir("generated/proto/desktopMain")

val generateProtos by tasks.registering {
    description = "Generates the protobuf/gRPC code from src/desktopMain/proto (${generatedProtoApis.keys})."
    group = "build"
    val apiDirs = generatedProtoApis.keys.map { protoSourceDir.dir(it) }
    inputs.files(apiDirs).withPropertyName("protos")
    inputs.files(protocTools).withPropertyName("protocTools")
    outputs.dir(generatedProtoDir)

    doLast {
        val tools = protocTools.files
        fun tool(prefix: String) = tools.single { it.name.startsWith(prefix) }
        val protoc = tool("protoc-$protobufVersion").apply { setExecutable(true) }
        val grpcJava = tool("protoc-gen-grpc-java").apply { setExecutable(true) }
        val grpcKotlinJar = tool("protoc-gen-grpc-kotlin")
        val protobufJar = tool("protobuf-java-$protobufVersion")

        // protoc plugins must be executables: wrap the grpc-kotlin jar.
        val work = temporaryDir
        val grpcKotlin = File(work, "protoc-gen-grpckt").apply {
            writeText("#!/bin/sh\nexec \"${System.getProperty("java.home")}/bin/java\" -jar \"$grpcKotlinJar\" \"\$@\"\n")
            setExecutable(true)
        }
        val wellKnownTypes = File(work, "wkt").apply { deleteRecursively() }
        project.copy {
            from(project.zipTree(protobufJar)) { include("google/protobuf/*.proto") }
            into(wellKnownTypes)
        }

        val out = generatedProtoDir.get().asFile.apply { deleteRecursively(); mkdirs() }
        generatedProtoApis.forEach { (folder, includeRoot) ->
            val protos = protoSourceDir.dir(folder).asFileTree.matching { include("**/*.proto") }.files.sorted()
            project.exec {
                commandLine(
                    listOf(
                        protoc.absolutePath,
                        "-I", protoSourceDir.dir(includeRoot).asFile.absolutePath,
                        "-I", wellKnownTypes.absolutePath,
                        "--java_out=$out", "--kotlin_out=$out",
                        "--plugin=protoc-gen-grpc-java=$grpcJava", "--grpc-java_out=$out",
                        "--plugin=protoc-gen-grpckt=$grpcKotlin", "--grpckt_out=$out",
                    ) + protos.map { it.absolutePath }
                )
            }
        }
    }
}

// The generated code is part of desktopMain: Kotlin (and kapt) see the Java
// and Kotlin files, javac compiles the Java ones.
kotlin.sourceSets.getByName("desktopMain").kotlin.srcDir(generateProtos.map { generatedProtoDir })
java.sourceSets.getByName("main").java.srcDir(generateProtos.map { generatedProtoDir })
tasks.matching { it.name.startsWith("compile") && it.name.contains("Desktop") || it.name.startsWith("kapt") || it.name == "compileJava" }
    .configureEach { dependsOn(generateProtos) }
